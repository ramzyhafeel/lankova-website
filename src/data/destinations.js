export function getDestination(slugOrName) {
  const query = (slugOrName || '').toLowerCase().replace(/[^a-z0-9]/g, '');
  return destinations.find(
    (d) =>
      d.slug.toLowerCase().replace(/[^a-z0-9]/g, '') === query ||
      d.name.toLowerCase().replace(/[^a-z0-9]/g, '') === query
  );
}

